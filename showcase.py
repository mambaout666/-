"""One template shared by Python export and the authenticated Edge extension."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def template():
    root = ROOT / "web"
    return ((root / "template.html").read_text(encoding="utf-8")
            .replace("/*__STYLE__*/", (root / "style.css").read_text(encoding="utf-8"))
            .replace("/*__APP__*/", (root / "app.js").read_text(encoding="utf-8")))


def render(report, config=None):
    if config is None: config = json.loads((ROOT / "web/config.json").read_text(encoding="utf-8"))
    # Split fixed slots before substitution so strings in data cannot become template tokens.
    before, rest = template().split("__REPORT_JSON__")
    between, after = rest.split("__CONFIG_JSON__")
    safe = lambda value: json.dumps(value, ensure_ascii=False).replace("<", "\\u003c")
    return before + safe(report) + between + safe(config) + after


def build_extension():
    source = template(); before, rest = source.split("__REPORT_JSON__"); between, after = rest.split("__CONFIG_JSON__")
    config = json.loads((ROOT / "web/config.json").read_text(encoding="utf-8"))
    code = "// Generated by showcase.py from web/; edit the source template, not this file.\n"
    code += "globalThis.ZZZShowcase = (() => {\n"
    code += "const chunks = " + json.dumps([before, between, after], ensure_ascii=False) + ";\n"
    code += "const defaults = " + json.dumps(config, ensure_ascii=False) + ";\n"
    code += "const safe = value => JSON.stringify(value).replaceAll('<', '\\\\u003c');\n"
    code += "return {render(report, config=defaults) {return chunks[0]+safe(report)+chunks[1]+safe(config)+chunks[2]}};\n})();\n"
    (ROOT / "edge-extension/showcase.js").write_text(code, encoding="utf-8")


if __name__ == "__main__":
    build_extension()
    print("Shared Edge template rebuilt")
